# The game's pronunciation tables (Kokoro's sound numbers, the names' spellings, the spelling rules) from the web layer's
# announcer-voice.ts into C++ for the native voice (Source/AirportDynastyPro/Private/G2P.cpp includes G2PTables.inl).
# Run again whenever announcer-voice.ts / g2p.ts change:  python Tools/make_g2p_tables.py
import re, json, os
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
t = open(os.path.join(ROOT, 'Airline-Manager-Pro-Babylon/src/ui/announcer-voice.ts'), encoding='utf-8').read()

def cs(s):
    # a wide string literal, every non-ASCII character as a \x escape (closed off so the next letter can't join it)
    parts = []
    for ch in s:
        o = ord(ch)
        if o < 128 and ch not in '"\\':
            parts.append(ch)
        else:
            parts.append('" L"\\x%04X" L"' % o)
    return ('L"' + ''.join(parts) + '"').replace(' L""', '')

ids = json.loads(re.search(r'const KOKORO_IDS[^=]*=\s*(\{.*?\});', t).group(1))
names = re.findall(r"'([^']+)':\s*'([^']+)'", re.search(r'NAMES:\s*\{(.*?)\}\s*as', t, re.S).group(1))
rules = re.findall(r"\['([^']*)',\s*'([^']*)',\s*'([^']*)'\]", re.search(r'RULES:\s*\[(.*?)\]\s*as string', t, re.S).group(1))
L = ["// Generated by Tools/make_g2p_tables.py from Airline-Manager-Pro-Babylon/src/ui/announcer-voice.ts - do not edit by hand.",
     '#pragma once', 'namespace ADPG2PTables', '{']
L.append('\tstruct FId { uint32 C; int64 Id; };')
L.append('\tstatic const FId KokoroIds[] = {' + ', '.join('{0x%X, %d}' % (ord(k), v) for k, v in ids.items()) + '};')
L.append('\tstruct FPair { const wchar_t* A; const wchar_t* B; };')
L.append('\tstatic const FPair Names[] = {' + ', '.join('{%s, %s}' % (cs(k), cs(v)) for k, v in names) + '};')
L.append('\tstatic const FPair Rules[] = {' + ', '.join('{%s, %s}' % (cs(a), cs(c)) for a, b, c in rules) + '};   // (spelling, British sound)')
L.append('}')
open(os.path.join(ROOT, 'Source/AirportDynastyPro/Private/G2PTables.inl'), 'w', encoding='utf-8').write('\n'.join(L) + '\n')
print(len(ids), 'ids,', len(names), 'names,', len(rules), 'rules')
